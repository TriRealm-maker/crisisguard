import { useEffect, useState } from 'react';
import { api } from '../services/api';
import { Coordinates } from '../types';
import { ChartBarIcon, ExclamationTriangleIcon, ArrowPathIcon } from '@heroicons/react/24/outline';

interface Props {
  coords: Coordinates | null;
}

export const PredictionPage = ({ coords }: Props) => {
  const [prediction, setPrediction] = useState<string>('');
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);

  const fetchPrediction = () => {
    if (!coords) return;
    setLoading(true);
    setError(null);
    api.prediction.get(coords.lat, coords.lng)
      .then((data) => {
        setPrediction(data.prediction || '');
      })
      .catch((err) => {
        setError('Failed to generate prediction');
        console.error(err);
      })
      .finally(() => setLoading(false));
  };

  useEffect(() => {
    if (coords) fetchPrediction();
  }, [coords]);

  if (!coords) {
    return (
      <div className="bg-white dark:bg-slate-800 rounded-xl p-8 text-center border border-slate-200 dark:border-slate-700">
        <ExclamationTriangleIcon className="h-12 w-12 mx-auto text-slate-400 mb-2" />
        <p className="text-slate-500">Location required for prediction</p>
      </div>
    );
  }

  return (
    <div className="bg-white dark:bg-slate-800 rounded-xl shadow-lg border border-slate-200 dark:border-slate-700 overflow-hidden">
      <div className="bg-slate-50 dark:bg-slate-850 p-6 border-b border-slate-200 dark:border-slate-700 flex items-center justify-between">
        <div className="flex items-center">
          <ChartBarIcon className="h-6 w-6 text-red-600 dark:text-red-400 mr-2" />
          <h2 className="text-xl font-bold text-slate-800 dark:text-white">AI Risk Assessment</h2>
        </div>
        <button
          onClick={fetchPrediction}
          disabled={loading}
          className="p-2 hover:bg-slate-200 dark:hover:bg-slate-700 rounded-lg transition-colors"
          title="Refresh"
        >
          <ArrowPathIcon className={`h-5 w-5 ${loading ? 'animate-spin' : ''}`} />
        </button>
      </div>
      
      <div className="p-6">
        {loading ? (
          <div className="space-y-4 animate-pulse">
            <div className="h-4 bg-slate-200 dark:bg-slate-700 rounded w-3/4"></div>
            <div className="h-4 bg-slate-200 dark:bg-slate-700 rounded w-full"></div>
            <div className="h-4 bg-slate-200 dark:bg-slate-700 rounded w-5/6"></div>
            <div className="h-32 bg-slate-100 dark:bg-slate-700 rounded mt-4"></div>
          </div>
        ) : error ? (
          <div className="text-center py-8">
            <ExclamationTriangleIcon className="h-12 w-12 mx-auto text-red-400 mb-2" />
            <p className="text-red-500">{error}</p>
            <button onClick={fetchPrediction} className="mt-4 px-4 py-2 bg-red-600 text-white rounded-lg">
              Try Again
            </button>
          </div>
        ) : (
          <div className="prose prose-slate dark:prose-invert max-w-none">
            <div className="whitespace-pre-wrap text-slate-700 dark:text-slate-300 leading-relaxed">
              {prediction}
            </div>
          </div>
        )}
      </div>

      <div className="bg-red-50 dark:bg-red-900/10 p-4 border-t border-red-100 dark:border-red-900/30">
        <p className="text-xs text-red-600 dark:text-red-400 text-center font-medium">
          DISCLAIMER: This prediction is generated by AI. Always follow official government warnings.
        </p>
      </div>
    </div>
  );
};
